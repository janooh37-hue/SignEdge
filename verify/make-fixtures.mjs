// Generates base64 PDF fixtures for the runtime verification harness.
// Uses the installed pdf-lib (same library the extension vendors).
import { PDFDocument, StandardFonts, rgb, degrees } from 'pdf-lib';
import { writeFile } from 'node:fs/promises';

async function textPdf(labels, rotate = 0) {
  const doc = await PDFDocument.create();
  const font = await doc.embedFont(StandardFonts.HelveticaBold);
  for (const label of labels) {
    const page = doc.addPage([612, 792]);
    if (rotate) page.setRotation(degrees(rotate));
    page.drawText(label, { x: 60, y: 700, size: 40, font, color: rgb(0, 0, 0) });
    page.drawText('BOTTOM', { x: 60, y: 60, size: 18, font, color: rgb(0, 0, 0) });
  }
  return await doc.saveAsBase64();
}

const NORMAL_B64 = await textPdf(['PAGE 1', 'PAGE 2', 'PAGE 3']);
const ROT90_B64 = await textPdf(['ROTATED 90'], 90);
const ROT270_B64 = await textPdf(['ROTATED 270'], 270);

const js = `// AUTO-GENERATED by make-fixtures.mjs — base64 PDF bytes for the verify harness.
export const NORMAL_B64 = ${JSON.stringify(NORMAL_B64)};
export const ROT90_B64 = ${JSON.stringify(ROT90_B64)};
export const ROT270_B64 = ${JSON.stringify(ROT270_B64)};
`;
await writeFile(new URL('./fixtures.js', import.meta.url), js);
console.log('wrote fixtures.js:', NORMAL_B64.length, ROT90_B64.length, ROT270_B64.length, 'b64 chars');
